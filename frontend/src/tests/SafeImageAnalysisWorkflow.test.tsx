/**
 * Comprehensive frontend tests for SafeImageAnalysisWorkflow.
 * Validates upload interaction, preview rendering, client-side validation,
 * error state rendering, results presentation, and case association.
 */

import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import { SafeImageAnalysisWorkflow } from '../components/image/SafeImageAnalysisWorkflow';
import * as imageService from '../services/imageService';
import * as caseService from '../services/caseService';
import { ApiError } from '../services/api';
import { ImageAssessmentResponse } from '../types/imageAnalysis';

// Mock Mocked Response Object
const mockAssessmentResponse: ImageAssessmentResponse = {
  assessment_id: '11111111-2222-3333-4444-555555555555',
  image_id: null,
  detector_name: 'SafeHER-Baseline-ELA-Heuristics',
  detector_version: '1.0.0',
  detection_task: 'hybrid_manipulation',
  raw_model_score: 0.55,
  is_calibrated: false,
  confidence_score: null,
  assessment_label: 'suspicious_manipulation',
  uncertainty_state: 'moderate',
  manipulation_regions: [
    {
      box_normalized: [0.25, 0.25, 0.5, 0.5],
      anomaly_score: 0.72,
      region_type: 'grid_cell',
      description: 'Compression error variance outlier in grid quadrant (2,2).',
    },
  ],
  preprocessing_warnings: [],
  explanation: 'The detector evaluated this JPEG image by inspecting Error Level Analysis compression residuals.',
  model_limitations: [
    'A negative detection result indicates the absence of detected manipulation signatures; it does NOT prove authenticity.',
    'Social-media platform recompression degrades micro-forensic signals.',
  ],
  metadata_summary: {
    format: 'JPEG',
    dimensions: [256, 256],
    size_bytes: 12400,
    sha256: 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855',
    has_exif: false,
    sanitized_exif: {},
    color_mode: 'RGB',
  },
  analysis_timestamp: '2026-11-24T06:00:00Z',
  disclaimer: 'DISCLAIMER: This automated preliminary image assessment is generated by an assistive AI system...',
};

describe('SafeImageAnalysisWorkflow Component', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    // Stub URL.createObjectURL and URL.revokeObjectURL
    window.URL.createObjectURL = vi.fn(() => 'blob:mock-image-preview-url');
    window.URL.revokeObjectURL = vi.fn();
  });

  it('renders initial dropzone with accessibility attributes', () => {
    render(<SafeImageAnalysisWorkflow />);
    expect(screen.getByText(/Drag and drop evidence image here/i)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: /Upload evidence image for deepfake/i })).toBeInTheDocument();
  });

  it('rejects unsupported file formats client-side', async () => {
    render(<SafeImageAnalysisWorkflow />);
    const file = new File(['text content'], 'evidence.txt', { type: 'text/plain' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [file] });
    fireEvent.change(input);

    expect(await screen.findByRole('alert')).toHaveTextContent(/Unsupported format/i);
    expect(screen.queryByText(/Ready for Analysis/i)).not.toBeInTheDocument();
  });

  it('rejects empty files client-side', async () => {
    render(<SafeImageAnalysisWorkflow />);
    const emptyFile = new File([], 'empty.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [emptyFile] });
    fireEvent.change(input);

    expect(await screen.findByRole('alert')).toHaveTextContent(/The selected file is empty/i);
  });

  it('displays preview card and file details on valid selection', async () => {
    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'suspect_photo.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    expect(await screen.findByText('suspect_photo.jpg')).toBeInTheDocument();
    expect(screen.getByText(/Client validation passed/i)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: /Run Deepfake & Manipulation Scan/i })).toBeInTheDocument();
  });

  it('cleans up object URL and state when removing selected file', async () => {
    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'suspect_photo.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const changeBtn = await screen.findByRole('button', { name: /Change file/i });
    fireEvent.click(changeBtn);

    expect(window.URL.revokeObjectURL).toHaveBeenCalledWith('blob:mock-image-preview-url');
    expect(screen.getByText(/Drag and drop evidence image here/i)).toBeInTheDocument();
  });

  it('advances through stages and displays structured results upon successful scan', async () => {
    vi.spyOn(imageService, 'assessImageEvidence').mockResolvedValueOnce(mockAssessmentResponse);

    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'evidence.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const scanBtn = await screen.findByRole('button', { name: /Run Deepfake & Manipulation Scan/i });
    fireEvent.click(scanBtn);

    // Should render results after completion
    await waitFor(() => {
      expect(screen.getByText(/Suspicious Anomalies/i)).toBeInTheDocument();
    });

    expect(screen.getByText('0.55')).toBeInTheDocument();
    expect(screen.getByText(/Uncalibrated Heuristic/i)).toBeInTheDocument();
    expect(screen.getByText(/SafeHER-Baseline-ELA-Heuristics/i)).toBeInTheDocument();
    expect(screen.getByText(/Moderate Uncertainty/i)).toBeInTheDocument();
    expect(screen.getByText(/Technical Analysis Summary/i)).toBeInTheDocument();
  });

  it('handles 401 unauthenticated error gracefully', async () => {
    vi.spyOn(imageService, 'assessImageEvidence').mockRejectedValueOnce(
      new ApiError(401, 'Authentication required.')
    );

    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'evidence.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const scanBtn = await screen.findByRole('button', { name: /Run Deepfake & Manipulation Scan/i });
    fireEvent.click(scanBtn);

    expect(await screen.findByRole('alert')).toHaveTextContent(
      /Authentication session expired. Please log in to evaluate evidence/i
    );
  });

  it('handles 403 unauthorized case permission error gracefully', async () => {
    vi.spyOn(imageService, 'assessImageEvidence').mockRejectedValueOnce(
      new ApiError(403, 'Not authorized to access this case.')
    );

    render(<SafeImageAnalysisWorkflow initialCaseId="unowned-case-id" />);
    const validFile = new File(['test-image-content'], 'evidence.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const scanBtn = await screen.findByRole('button', { name: /Run Deepfake & Manipulation Scan/i });
    fireEvent.click(scanBtn);

    expect(await screen.findByRole('alert')).toHaveTextContent(
      /You do not have authorization to associate evidence with this case/i
    );
  });

  it('allows case association from results dashboard', async () => {
    vi.spyOn(imageService, 'assessImageEvidence')
      .mockResolvedValueOnce(mockAssessmentResponse)
      .mockResolvedValueOnce({
        ...mockAssessmentResponse,
        image_id: 'preserved-evidence-uuid-999',
      });

    vi.spyOn(caseService, 'fetchUserCases').mockResolvedValueOnce([
      {
        id: 'case-uuid-1',
        owner_id: 'user-uuid-1',
        title: 'Harassment Case Alpha',
        description: 'Case description',
        status: 'open',
        created_at: '2026-11-24T00:00:00Z',
      },
    ]);

    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'evidence.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const scanBtn = await screen.findByRole('button', { name: /Run Deepfake & Manipulation Scan/i });
    fireEvent.click(scanBtn);

    const associateBtn = await screen.findByRole('button', { name: /Associate with Incident Case/i });
    fireEvent.click(associateBtn);

    expect(await screen.findByText(/Associate Evidence with Incident Case/i)).toBeInTheDocument();
    expect(await screen.findByText(/Harassment Case Alpha/i)).toBeInTheDocument();

    const confirmBtn = screen.getByRole('button', { name: /Save & Associate/i });
    fireEvent.click(confirmBtn);

    await waitFor(() => {
      expect(screen.getByRole('status')).toHaveTextContent(/Evidence was uploaded, integrity-checked/i);
    });
  });

  it('handles second-upload case association failure while preserving existing assessment', async () => {
    const assessSpy = vi.spyOn(imageService, 'assessImageEvidence')
      .mockResolvedValueOnce(mockAssessmentResponse)
      .mockRejectedValueOnce(new ApiError(500, 'Database commit lock failure'));

    vi.spyOn(caseService, 'fetchUserCases').mockResolvedValueOnce([
      {
        id: 'case-uuid-1',
        owner_id: 'user-uuid-1',
        title: 'Harassment Case Alpha',
        description: 'Case description',
        status: 'open',
        created_at: '2026-11-24T00:00:00Z',
      },
    ]);

    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'evidence.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const scanBtn = await screen.findByRole('button', { name: /Run Deepfake & Manipulation Scan/i });
    fireEvent.click(scanBtn);

    const associateBtn = await screen.findByRole('button', { name: /Associate with Incident Case/i });
    fireEvent.click(associateBtn);

    const confirmBtn = await screen.findByRole('button', { name: /Save & Associate/i });
    fireEvent.click(confirmBtn);

    // Verify error is displayed
    await waitFor(() => {
      expect(screen.getByRole('alert')).toHaveTextContent(/Case association failed: Database commit lock failure/i);
    });

    // Verify existing assessment remains visible and intact
    expect(screen.getByText(/Forensic Visual Overlay/i)).toBeInTheDocument();

    // Verify both calls used the exact same File instance
    expect(assessSpy).toHaveBeenCalledTimes(2);
    expect(assessSpy).toHaveBeenNthCalledWith(1, validFile, undefined);
    expect(assessSpy).toHaveBeenNthCalledWith(2, validFile, 'case-uuid-1');
  });

  it('handles request timeout (504) gracefully with actionable feedback', async () => {
    vi.spyOn(imageService, 'assessImageEvidence').mockRejectedValueOnce(
      new ApiError(504, 'The forensic analysis request timed out.')
    );

    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'evidence.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const scanBtn = await screen.findByRole('button', { name: /Run Deepfake & Manipulation Scan/i });
    fireEvent.click(scanBtn);

    expect(await screen.findByRole('alert')).toHaveTextContent(
      /The forensic analysis request timed out. Please try again with an optimized image/i
    );
  });

  it('handles network failure gracefully', async () => {
    vi.spyOn(imageService, 'assessImageEvidence').mockRejectedValueOnce(
      new TypeError('Failed to fetch')
    );

    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'evidence.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const scanBtn = await screen.findByRole('button', { name: /Run Deepfake & Manipulation Scan/i });
    fireEvent.click(scanBtn);

    expect(await screen.findByRole('alert')).toHaveTextContent(
      /Network connection failure. Please check your internet connection or server availability/i
    );
  });

  it('handles 429 rate limit / inference capacity gracefully', async () => {
    vi.spyOn(imageService, 'assessImageEvidence').mockRejectedValueOnce(
      new ApiError(429, 'Rate limit exceeded')
    );

    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'evidence.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const scanBtn = await screen.findByRole('button', { name: /Run Deepfake & Manipulation Scan/i });
    fireEvent.click(scanBtn);

    expect(await screen.findByRole('alert')).toHaveTextContent(
      /Inference service rate limit or capacity reached. Please wait before submitting another request/i
    );
  });

  it('prevents duplicate submissions while analysis is in progress', async () => {
    let resolveAnalysis: (val: ImageAssessmentResponse) => void = () => {};
    const analysisPromise = new Promise<ImageAssessmentResponse>((resolve) => {
      resolveAnalysis = resolve;
    });

    const assessSpy = vi.spyOn(imageService, 'assessImageEvidence').mockImplementation(() => analysisPromise);

    render(<SafeImageAnalysisWorkflow />);
    const validFile = new File(['test-image-content'], 'evidence.jpg', { type: 'image/jpeg' });

    const input = document.querySelector('input[type="file"]') as HTMLInputElement;
    Object.defineProperty(input, 'files', { value: [validFile] });
    fireEvent.change(input);

    const scanBtn = await screen.findByRole('button', { name: /Run Deepfake & Manipulation Scan/i });

    // First click initiates processing
    fireEvent.click(scanBtn);

    // Verify stage container renders with accessible status and live region
    const statusContainer = await screen.findByRole('status');
    expect(statusContainer).toHaveAttribute('aria-live', 'polite');

    // Button container is replaced by processing stages to prevent double submits
    expect(screen.queryByRole('button', { name: /Run Deepfake & Manipulation Scan/i })).not.toBeInTheDocument();

    // Repeated clicks on the original detached element or handler should be ignored
    fireEvent.click(scanBtn);
    fireEvent.click(scanBtn);

    // Resolve the promise
    resolveAnalysis(mockAssessmentResponse);

    await waitFor(() => {
      expect(screen.getByText(/Suspicious Anomalies/i)).toBeInTheDocument();
    });

    // Only one API call should have been made
    expect(assessSpy).toHaveBeenCalledTimes(1);
  });
});
